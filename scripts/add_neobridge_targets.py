#!/usr/bin/env python3
"""Add the NeoOSBridge targets to the checked-in Xcode project.

The project is generated by XcodeGen, but the checked-in `project.pbxproj` also carries hand edits
that the spec does not reproduce (a real DEVELOPMENT_TEAM, `org.neil.*` bundle identifiers,
STRING_CATALOG_GENERATE_SYMBOLS). Regenerating would silently drop them, so this script inserts the
new objects instead of rewriting the file. It is idempotent: running it twice changes nothing.
"""
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROJECT = ROOT / "HermesIOS.xcodeproj" / "project.pbxproj"

T = "\t\t"
T3 = "\t\t\t"
T4 = "\t\t\t\t"

APP_SOURCES = ["NeoOSBridgeApp.swift", "BridgeController.swift", "BridgeEnvironment.swift",
               "BridgeSettingsView.swift", "BridgeRequestsView.swift"]
TEST_SOURCES = ["BridgeControllerTests.swift"]
PRODUCTS = ["CloudBridgeCore", "CloudBridgeSync", "HermesBridgeClient"]


def uid(name):
    """Deterministic 24-hex identifier, so re-running produces the same file."""
    return hashlib.md5(("neobridge:" + name).encode()).hexdigest().upper()[:24]


def insert_before(text, marker, block):
    index = text.index(marker)
    return text[:index] + block + text[index:]


def main():
    text = PROJECT.read_text()
    if "NeoOSBridge */ = {" in text:
        print("NeoOSBridge targets already present; nothing to do")
        return 0

    ids = {
        "app_target": uid("target:app"),
        "test_target": uid("target:tests"),
        "app_product": uid("product:app"),
        "test_product": uid("product:tests"),
        "app_group": uid("group:app"),
        "resources_group": uid("group:resources"),
        "test_group": uid("group:tests"),
        "entitlements": uid("file:entitlements"),
        "info": uid("file:info"),
        "local_package": uid("package:local"),
        "app_debug": uid("config:app:debug"),
        "app_release": uid("config:app:release"),
        "tests_debug": uid("config:tests:debug"),
        "tests_release": uid("config:tests:release"),
        "app_config_list": uid("configlist:app"),
        "test_config_list": uid("configlist:tests"),
        "sources_app": uid("phase:sources:app"),
        "frameworks_app": uid("phase:frameworks:app"),
        "resources_app": uid("phase:resources:app"),
        "sources_tests": uid("phase:sources:tests"),
        "dependency": uid("dependency:tests"),
        "proxy": uid("proxy:tests"),
    }
    build_file = {name: uid("buildfile:" + name) for name in APP_SOURCES + TEST_SOURCES}
    file_ref = {name: uid("fileref:" + name) for name in APP_SOURCES + TEST_SOURCES}
    product_build = {name: uid("buildfile:product:" + name) for name in PRODUCTS}
    product_dep = {name: uid("productdep:" + name) for name in PRODUCTS}

    build_files = []
    for name in APP_SOURCES + TEST_SOURCES:
        build_files.append(T + "%s /* %s in Sources */ = {isa = PBXBuildFile; fileRef = %s /* %s */; };\n"
                           % (build_file[name], name, file_ref[name], name))
    for name in PRODUCTS:
        build_files.append(T + "%s /* %s in Frameworks */ = {isa = PBXBuildFile; productRef = %s /* %s */; };\n"
                           % (product_build[name], name, product_dep[name], name))

    proxy = (T + "%s /* PBXContainerItemProxy */ = {\n" % ids["proxy"]
             + T3 + "isa = PBXContainerItemProxy;\n"
             + T3 + "containerPortal = AF054738A80FFFF2F67365FA /* Project object */;\n"
             + T3 + "proxyType = 1;\n"
             + T3 + "remoteGlobalIDString = %s;\n" % ids["app_target"]
             + T3 + "remoteInfo = NeoOSBridge;\n"
             + T + "};\n")

    file_references = []
    file_references.append(T + "%s /* NeoOSBridge.app */ = {isa = PBXFileReference; "
                               "explicitFileType = wrapper.application; includeInIndex = 0; "
                               "path = NeoOSBridge.app; sourceTree = BUILT_PRODUCTS_DIR; };\n"
                           % ids["app_product"])
    file_references.append(T + "%s /* NeoOSBridgeTests.xctest */ = {isa = PBXFileReference; "
                               "explicitFileType = wrapper.cfbundle; includeInIndex = 0; "
                               "path = NeoOSBridgeTests.xctest; sourceTree = BUILT_PRODUCTS_DIR; };\n"
                           % ids["test_product"])
    for name in APP_SOURCES + TEST_SOURCES:
        file_references.append(T + '%s /* %s */ = {isa = PBXFileReference; '
                                   'lastKnownFileType = sourcecode.swift; path = %s; sourceTree = "<group>"; };\n'
                               % (file_ref[name], name, name))
    file_references.append(T + '%s /* Info.plist */ = {isa = PBXFileReference; '
                               'lastKnownFileType = text.plist.xml; path = Info.plist; sourceTree = "<group>"; };\n'
                           % ids["info"])
    file_references.append(T + '%s /* NeoOSBridge.entitlements */ = {isa = PBXFileReference; '
                               'lastKnownFileType = text.plist.entitlements; path = NeoOSBridge.entitlements; '
                               'sourceTree = "<group>"; };\n'
                           % ids["entitlements"])

    frameworks_phase = (T + "%s /* Frameworks */ = {\n" % ids["frameworks_app"]
                        + T3 + "isa = PBXFrameworksBuildPhase;\n"
                        + T3 + "buildActionMask = 2147483647;\n"
                        + T3 + "files = (\n"
                        + "".join(T4 + "%s /* %s in Frameworks */,\n" % (product_build[n], n) for n in PRODUCTS)
                        + T3 + ");\n"
                        + T3 + "runOnlyForDeploymentPostprocessing = 0;\n"
                        + T + "};\n")
    resources_phase = (T + "%s /* Resources */ = {\n" % ids["resources_app"]
                       + T3 + "isa = PBXResourcesBuildPhase;\n"
                       + T3 + "buildActionMask = 2147483647;\n"
                       + T3 + "files = (\n"
                       + T3 + ");\n"
                       + T3 + "runOnlyForDeploymentPostprocessing = 0;\n"
                       + T + "};\n")

    def sources_phase(identifier, names):
        return (T + "%s /* Sources */ = {\n" % identifier
                + T3 + "isa = PBXSourcesBuildPhase;\n"
                + T3 + "buildActionMask = 2147483647;\n"
                + T3 + "files = (\n"
                + "".join(T4 + "%s /* %s in Sources */,\n" % (build_file[n], n) for n in names)
                + T3 + ");\n"
                + T3 + "runOnlyForDeploymentPostprocessing = 0;\n"
                + T + "};\n")

    app_group = (T + "%s /* NeoOSBridge */ = {\n" % ids["app_group"]
                 + T3 + "isa = PBXGroup;\n"
                 + T3 + "children = (\n"
                 + "".join(T4 + "%s /* %s */,\n" % (file_ref[n], n) for n in APP_SOURCES)
                 + T4 + "%s /* NeoOSBridge.entitlements */,\n" % ids["entitlements"]
                 + T4 + "%s /* Resources */,\n" % ids["resources_group"]
                 + T3 + ");\n"
                 + T3 + "path = NeoOSBridge;\n"
                 + T3 + 'sourceTree = "<group>";\n'
                 + T + "};\n")
    resources_group = (T + "%s /* Resources */ = {\n" % ids["resources_group"]
                       + T3 + "isa = PBXGroup;\n"
                       + T3 + "children = (\n"
                       + T4 + "%s /* Info.plist */,\n" % ids["info"]
                       + T3 + ");\n"
                       + T3 + "path = Resources;\n"
                       + T3 + 'sourceTree = "<group>";\n'
                       + T + "};\n")
    test_group = (T + "%s /* NeoOSBridgeTests */ = {\n" % ids["test_group"]
                  + T3 + "isa = PBXGroup;\n"
                  + T3 + "children = (\n"
                  + "".join(T4 + "%s /* %s */,\n" % (file_ref[n], n) for n in TEST_SOURCES)
                  + T3 + ");\n"
                  + T3 + "path = NeoOSBridgeTests;\n"
                  + T3 + 'sourceTree = "<group>";\n'
                  + T + "};\n")

    app_target = (T + "%s /* NeoOSBridge */ = {\n" % ids["app_target"]
                  + T3 + "isa = PBXNativeTarget;\n"
                  + T3 + 'buildConfigurationList = %s /* Build configuration list for PBXNativeTarget "NeoOSBridge" */;\n'
                  % ids["app_config_list"]
                  + T3 + "buildPhases = (\n"
                  + T4 + "%s /* Sources */,\n" % ids["sources_app"]
                  + T4 + "%s /* Resources */,\n" % ids["resources_app"]
                  + T4 + "%s /* Frameworks */,\n" % ids["frameworks_app"]
                  + T3 + ");\n"
                  + T3 + "buildRules = (\n" + T3 + ");\n"
                  + T3 + "dependencies = (\n" + T3 + ");\n"
                  + T3 + "name = NeoOSBridge;\n"
                  + T3 + "packageProductDependencies = (\n"
                  + "".join(T4 + "%s /* %s */,\n" % (product_dep[n], n) for n in PRODUCTS)
                  + T3 + ");\n"
                  + T3 + "productName = NeoOSBridge;\n"
                  + T3 + "productReference = %s /* NeoOSBridge.app */;\n" % ids["app_product"]
                  + T3 + 'productType = "com.apple.product-type.application";\n'
                  + T + "};\n")
    test_target = (T + "%s /* NeoOSBridgeTests */ = {\n" % ids["test_target"]
                   + T3 + "isa = PBXNativeTarget;\n"
                   + T3 + 'buildConfigurationList = %s /* Build configuration list for PBXNativeTarget "NeoOSBridgeTests" */;\n'
                   % ids["test_config_list"]
                   + T3 + "buildPhases = (\n"
                   + T4 + "%s /* Sources */,\n" % ids["sources_tests"]
                   + T3 + ");\n"
                   + T3 + "buildRules = (\n" + T3 + ");\n"
                   + T3 + "dependencies = (\n"
                   + T4 + "%s /* PBXTargetDependency */,\n" % ids["dependency"]
                   + T3 + ");\n"
                   + T3 + "name = NeoOSBridgeTests;\n"
                   + T3 + "packageProductDependencies = (\n" + T3 + ");\n"
                   + T3 + "productName = NeoOSBridgeTests;\n"
                   + T3 + "productReference = %s /* NeoOSBridgeTests.xctest */;\n" % ids["test_product"]
                   + T3 + 'productType = "com.apple.product-type.bundle.unit-test";\n'
                   + T + "};\n")

    target_dependency = (T + "%s /* PBXTargetDependency */ = {\n" % ids["dependency"]
                         + T3 + "isa = PBXTargetDependency;\n"
                         + T3 + "target = %s /* NeoOSBridge */;\n" % ids["app_target"]
                         + T3 + "targetProxy = %s /* PBXContainerItemProxy */;\n" % ids["proxy"]
                         + T + "};\n")

    app_settings = (
        T4 + "CODE_SIGN_ENTITLEMENTS = NeoOSBridge/NeoOSBridge.entitlements;\n"
        + T4 + "CODE_SIGN_STYLE = Automatic;\n"
        + T4 + "DEVELOPMENT_TEAM = S8X8W7J77M;\n"
        + T4 + "INFOPLIST_FILE = NeoOSBridge/Resources/Info.plist;\n"
        + T4 + "LD_RUNPATH_SEARCH_PATHS = (\n"
        + T4 + '\t"$(inherited)",\n'
        + T4 + '\t"@executable_path/../Frameworks",\n'
        + T4 + ");\n"
        + T4 + "MACOSX_DEPLOYMENT_TARGET = 14.0;\n"
        + T4 + "PRODUCT_BUNDLE_IDENTIFIER = org.neil.NeoOSBridge;\n"
        + T4 + "SDKROOT = macosx;\n")
    test_settings = (
        T4 + 'BUNDLE_LOADER = "$(TEST_HOST)";\n'
        + T4 + "CODE_SIGN_STYLE = Automatic;\n"
        + T4 + "DEVELOPMENT_TEAM = S8X8W7J77M;\n"
        + T4 + "GENERATE_INFOPLIST_FILE = YES;\n"
        + T4 + "LD_RUNPATH_SEARCH_PATHS = (\n"
        + T4 + '\t"$(inherited)",\n'
        + T4 + '\t"@executable_path/../Frameworks",\n'
        + T4 + '\t"@loader_path/../Frameworks",\n'
        + T4 + ");\n"
        + T4 + "MACOSX_DEPLOYMENT_TARGET = 14.0;\n"
        + T4 + "PRODUCT_BUNDLE_IDENTIFIER = org.neil.NeoOSBridgeTests;\n"
        + T4 + "SDKROOT = macosx;\n"
        + T4 + 'TEST_HOST = "$(BUILT_PRODUCTS_DIR)/NeoOSBridge.app/Contents/MacOS/NeoOSBridge";\n')

    def build_config(identifier, name, settings):
        return (T + "%s /* %s */ = {\n" % (identifier, name)
                + T3 + "isa = XCBuildConfiguration;\n"
                + T3 + "buildSettings = {\n"
                + settings
                + T3 + "};\n"
                + T3 + "name = %s;\n" % name
                + T + "};\n")

    build_configs = (build_config(ids["app_debug"], "Debug", app_settings)
                     + build_config(ids["app_release"], "Release", app_settings)
                     + build_config(ids["tests_debug"], "Debug", test_settings)
                     + build_config(ids["tests_release"], "Release", test_settings))

    def config_list(identifier, label, debug, release):
        return (T + '%s /* Build configuration list for PBXNativeTarget "%s" */ = {\n' % (identifier, label)
                + T3 + "isa = XCConfigurationList;\n"
                + T3 + "buildConfigurations = (\n"
                + T4 + "%s /* Debug */,\n" % debug
                + T4 + "%s /* Release */,\n" % release
                + T3 + ");\n"
                + T3 + "defaultConfigurationIsVisible = 0;\n"
                + T3 + "defaultConfigurationName = Debug;\n"
                + T + "};\n")

    config_lists = (config_list(ids["app_config_list"], "NeoOSBridge", ids["app_debug"], ids["app_release"])
                    + config_list(ids["test_config_list"], "NeoOSBridgeTests", ids["tests_debug"], ids["tests_release"]))

    local_package_block = ("/* Begin XCLocalSwiftPackageReference section */\n"
                           + T + '%s /* XCLocalSwiftPackageReference "Packages/NeoCloudBridge" */ = {\n'
                           % ids["local_package"]
                           + T3 + "isa = XCLocalSwiftPackageReference;\n"
                           + T3 + "relativePath = Packages/NeoCloudBridge;\n"
                           + T + "};\n"
                           + "/* End XCLocalSwiftPackageReference section */\n\n")
    product_dependencies = "".join(
        T + "%s /* %s */ = {\n" % (product_dep[name], name)
        + T3 + "isa = XCSwiftPackageProductDependency;\n"
        + T3 + 'package = %s /* XCLocalSwiftPackageReference "Packages/NeoCloudBridge" */;\n' % ids["local_package"]
        + T3 + "productName = %s;\n" % name
        + T + "};\n"
        for name in PRODUCTS)

    text = insert_before(text, "/* End PBXBuildFile section */", "".join(build_files))
    text = insert_before(text, "/* End PBXContainerItemProxy section */", proxy)
    text = insert_before(text, "/* End PBXFileReference section */", "".join(file_references))
    text = insert_before(text, "/* End PBXFrameworksBuildPhase section */", frameworks_phase)
    text = insert_before(text, "/* End PBXGroup section */", app_group + resources_group + test_group)
    text = insert_before(text, "/* End PBXNativeTarget section */", app_target + test_target)
    text = insert_before(text, "/* End PBXResourcesBuildPhase section */", resources_phase)
    text = insert_before(text, "/* End PBXSourcesBuildPhase section */",
                         sources_phase(ids["sources_app"], APP_SOURCES)
                         + sources_phase(ids["sources_tests"], TEST_SOURCES))
    text = insert_before(text, "/* End PBXTargetDependency section */", target_dependency)
    text = insert_before(text, "/* End XCBuildConfiguration section */", build_configs)
    text = insert_before(text, "/* End XCConfigurationList section */", config_lists)
    text = insert_before(text, "/* Begin XCRemoteSwiftPackageReference section */", local_package_block)
    text = insert_before(text, "/* End XCSwiftPackageProductDependency section */", product_dependencies)

    replacements = [
        (T4 + "1E7F5EC57CB7315E89A5C1F3 /* HermesIOSWidgets */,\n"
         + T4 + "53D3F01D3EBC6A92635B9684 /* Products */,\n",
         T4 + "1E7F5EC57CB7315E89A5C1F3 /* HermesIOSWidgets */,\n"
         + T4 + "%s /* NeoOSBridge */,\n" % ids["app_group"]
         + T4 + "%s /* NeoOSBridgeTests */,\n" % ids["test_group"]
         + T4 + "53D3F01D3EBC6A92635B9684 /* Products */,\n"),
        (T4 + "0950720749BFDC7C3C5A89A9 /* HermesIOSWidgets.appex */,\n",
         T4 + "0950720749BFDC7C3C5A89A9 /* HermesIOSWidgets.appex */,\n"
         + T4 + "%s /* NeoOSBridge.app */,\n" % ids["app_product"]
         + T4 + "%s /* NeoOSBridgeTests.xctest */,\n" % ids["test_product"]),
        (T4 + 'CBDF09291C7F7B4794398F30 /* XCRemoteSwiftPackageReference "WebRTC" */,\n',
         T4 + 'CBDF09291C7F7B4794398F30 /* XCRemoteSwiftPackageReference "WebRTC" */,\n'
         + T4 + '%s /* XCLocalSwiftPackageReference "Packages/NeoCloudBridge" */,\n' % ids["local_package"]),
        (T4 + "A408AB7B73A825E284FBCEBF /* HermesIOSUITests */,\n",
         T4 + "A408AB7B73A825E284FBCEBF /* HermesIOSUITests */,\n"
         + T4 + "%s /* NeoOSBridge */,\n" % ids["app_target"]
         + T4 + "%s /* NeoOSBridgeTests */,\n" % ids["test_target"]),
        (T4 + "\tCDBCE2E3BABBD3FF1069603C = {\n"
         + T4 + "\t\tProvisioningStyle = Automatic;\n"
         + T4 + "\t};\n",
         T4 + "\tCDBCE2E3BABBD3FF1069603C = {\n"
         + T4 + "\t\tProvisioningStyle = Automatic;\n"
         + T4 + "\t};\n"
         + T4 + "\t%s = {\n" % ids["app_target"]
         + T4 + "\t\tProvisioningStyle = Automatic;\n"
         + T4 + "\t};\n"
         + T4 + "\t%s = {\n" % ids["test_target"]
         + T4 + "\t\tProvisioningStyle = Automatic;\n"
         + T4 + "\t\tTestTargetID = %s;\n" % ids["app_target"]
         + T4 + "\t};\n"),
    ]
    for old, new in replacements:
        if old not in text:
            print("ERROR: cannot find insertion anchor:\n" + old, file=sys.stderr)
            return 1
        text = text.replace(old, new, 1)

    PROJECT.write_text(text)
    print("inserted NeoOSBridge and NeoOSBridgeTests into project.pbxproj")
    return 0


if __name__ == "__main__":
    sys.exit(main())
